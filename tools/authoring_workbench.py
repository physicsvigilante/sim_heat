"""Serve one admitted H1 study in the existing inspector, locally and read-only.

This is an offline source-facts workbench, NOT a solver, native runner, source
custody attestation, or upload service. It never writes model/study files.
"""
from __future__ import annotations

import argparse
from functools import partial
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
import json
from pathlib import Path
import sys
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
if __package__ in (None, ''):
    sys.path.insert(0, str(ROOT))

from h1.model import Refusal, require
from h1.source_preview import build_source_preview, serialized
from h1.study import load_study

VIEW = ROOT / 'viewer' / 'source_preview'
DEFAULT_ROUTE = '/viewer/source_preview/data/TEACH_SPLIT3.json'

# This is an intentional local-session alias for the fixed default JSON fetch
# in the already-reviewed generic viewer. Its response contains the *actual*
# admitted study ID and source hashes. Never copy or relabel a native result.
_REPLACE = {
    '<a href="../../index.html">Return to archived explorer entry</a>':
        '<a href="../../index.html">Local session instructions</a>',
    'Load the included TEACH_SPLIT3 demonstration or verify another payload generated by the offline H1 source-preview command.':
        'Your admitted H1 source loads automatically in this local session. Other admitted source-only JSON files can be inspected through the file picker.',
}

HELP = b'''<!doctype html><html lang="en"><head><meta charset="utf-8"><title>SIM_HEAT local authoring session</title>
<meta name="viewport" content="width=device-width,initial-scale=1"></head><body>
<main><h1>Local H1 source-preview session</h1><p><a href="viewer/source_preview/">Return to the source-only inspector</a>.</p>
<p>This session serves only a previously admitted H1 source description from memory. Its inputs are authored assumptions, not simulated values. No OpenModelica tool runs and no files are uploaded or modified.</p>
<p>Do not include secrets in model inputs or provenance notes. Any process on this computer that learns the local session port can read the admitted source preview; avoid shared/untrusted machines and press Ctrl+C after inspection.</p>
<p>To inspect the separate archived native diagnostic explorer, use the normal repository server as described in the README; this restricted session intentionally does not expose repository source files or archives.</p>
</main></body></html>'''


def _viewer_html() -> bytes:
    page = (VIEW / 'index.html').read_text(encoding='utf-8')
    for old, new in _REPLACE.items():
        require(page.count(old) == 1, 'source_preview', 'reviewed viewer default text changed')
        page = page.replace(old, new)
    return page.encode('utf-8')


def _resources(payload: bytes) -> dict[str, tuple[bytes, str]]:
    # Files are snapshotted before the server starts. No path is constructed
    # from a URL, model name, study ID, or remotely supplied string.
    return {
        '/viewer/source_preview/': (_viewer_html(), 'text/html; charset=utf-8'),
        '/viewer/source_preview/index.html': (_viewer_html(), 'text/html; charset=utf-8'),
        '/viewer/source_preview/app.mjs': ((VIEW / 'app.mjs').read_bytes(), 'text/javascript; charset=utf-8'),
        '/viewer/source_preview/core.mjs': ((VIEW / 'core.mjs').read_bytes(), 'text/javascript; charset=utf-8'),
        DEFAULT_ROUTE: (payload, 'application/json; charset=utf-8'),
        '/index.html': (HELP, 'text/html; charset=utf-8'),
    }


class PreviewHandler(BaseHTTPRequestHandler):
    """Exact-route only. Loopback, no uploads, writes, arbitrary file reads."""
    def __init__(self, *args, resources: dict[str, tuple[bytes, str]], **kwargs):
        self.resources = resources
        super().__init__(*args, **kwargs)

    def version_string(self) -> str:
        return 'SIM_HEAT-source-preview'

    def log_message(self, format: str, *args) -> None:
        # The teacher-facing CLI remains quiet; no source content is logged.
        pass

    def _send(self, status: int, data: bytes, mime: str, *, head: bool = False) -> None:
        self.send_response(status)
        self.send_header('Content-Type', mime)
        self.send_header('Content-Length', str(len(data)))
        self.send_header('Cache-Control', 'no-store')
        self.send_header('X-Content-Type-Options', 'nosniff')
        self.send_header('Referrer-Policy', 'no-referrer')
        self.send_header('Cross-Origin-Resource-Policy', 'same-origin')
        self.send_header('Content-Security-Policy',
                         "default-src 'none'; script-src 'self'; style-src 'unsafe-inline'; "
                         "connect-src 'self'; img-src 'self' data:; base-uri 'none'; "
                         "form-action 'none'; frame-ancestors 'none'")
        self.end_headers()
        if not head:
            self.wfile.write(data)

    def _route(self, *, head: bool = False) -> None:
        expected = f'127.0.0.1:{self.server.server_port}'
        hosts = self.headers.get_all('Host', [])
        if len(hosts) != 1 or hosts[0] != expected:
            self._send(421, b'Invalid Host\n', 'text/plain; charset=utf-8', head=head)
            return
        uri = urlsplit(self.path)
        if uri.scheme or uri.netloc or uri.query or uri.fragment or self.path != uri.path:
            self._send(404, b'Not found\n', 'text/plain; charset=utf-8', head=head)
            return
        if uri.path == '/':
            self.send_response(302)
            self.send_header('Location', '/viewer/source_preview/')
            self.send_header('Cache-Control', 'no-store')
            self.send_header('Content-Length', '0')
            self.end_headers()
            return
        if uri.path == '/favicon.ico':
            self._send(204, b'', 'text/plain; charset=utf-8', head=head)
            return
        resource = self.resources.get(uri.path)
        if resource is None:
            self._send(404, b'Not found\n', 'text/plain; charset=utf-8', head=head)
            return
        self._send(200, *resource, head=head)

    def do_GET(self) -> None:
        self._route()

    def do_HEAD(self) -> None:
        self._route(head=True)

    def do_POST(self) -> None:
        self._send(405, b'Writes forbidden\n', 'text/plain; charset=utf-8')

    do_PUT = do_DELETE = do_PATCH = do_POST


def create_server(study: Path, root: Path, port: int = 0) -> tuple[ThreadingHTTPServer, dict]:
    """Complete genuine H1 admission before opening any listening socket."""
    require(type(port) is int and 0 <= port <= 65535, 'path', 'port out of range')
    admitted = load_study(study, root)
    payload = build_source_preview(admitted)
    source_only = serialized(payload)
    resources = _resources(source_only)
    server = ThreadingHTTPServer(('127.0.0.1', port),
                                 partial(PreviewHandler, resources=resources))
    server.daemon_threads = True
    return server, payload


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('study', type=Path, help='Existing H1 study.json (never rewritten)')
    parser.add_argument('--root', type=Path, required=True, help='Trusted authored case root')
    parser.add_argument('--port', type=int, default=0, help='Loopback port (0 selects an available port)')
    args = parser.parse_args()
    try:
        server, preview = create_server(args.study, args.root, args.port)
    except (Refusal, OSError, UnicodeError, ValueError) as exc:
        print(json.dumps({'stage': 'local_authoring_workbench', 'admitted': False,
                          'nativeExecuted': False, 'code': getattr(exc, 'code', 'input_error'),
                          'reason': str(exc)}, allow_nan=False), file=sys.stderr)
        return 2
    try:
        print(json.dumps({'stage': 'local_authoring_workbench', 'admitted': True,
                          'nativeExecuted': False, 'studyId': preview['studyId'],
                          'modelSha256': preview['source']['modelSha256'],
                          'studySha256': preview['source']['studySha256'],
                          'url': f'http://127.0.0.1:{server.server_port}/viewer/source_preview/',
                          'publicRequestStatus': 'not_computed'}, allow_nan=False), flush=True)
        server.serve_forever(poll_interval=0.1)
    except KeyboardInterrupt:
        pass
    finally:
        server.server_close()
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
